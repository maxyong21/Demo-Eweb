import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readdir, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createDemoServer } from './serve.mjs';

// Uses an existing Playwright installation; does not add dependencies to the demo.
const require = createRequire(import.meta.url);
let chromium;
try { ({chromium} = require('playwright')); }
catch {
  const cache = path.join(process.env.LOCALAPPDATA || '', 'npm-cache', '_npx');
  for (const entry of await readdir(cache).catch(()=>[])) {
    try { ({chromium} = require(path.join(cache,entry,'node_modules','playwright'))); break; } catch { /* next cached install */ }
  }
}
if (!chromium) throw new Error('Playwright is required to run browser verification.');
const server = createDemoServer();
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  await page.emulateMedia({reducedMotion:'reduce'});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/proposal.html');
  assert.match(await page.title(),/Lucky Dotcom/);
  assert.match(await page.locator('#scenario-sales').innerText(),/57,750/);
  await page.locator('#monthly-orders').fill('200');
  assert.match(await page.locator('#scenario-sales').innerText(),/115,500/);
  await page.locator('#order-growth').fill('-30');
  await page.locator('#basket-growth').fill('-30');
  assert.match(await page.locator('#scenario-sales').innerText(),/49,000/);
  assert.match(await page.locator('#sales-difference').innerText(),/−/);
  await page.locator('#monthly-orders').fill('-1');
  assert.equal(await page.locator('#scenario-sales').innerText(),'—');
  await page.locator('#reset-scenario').click();
  await page.locator('#monthly-orders').fill('0');
  assert.equal(await page.locator('#monthly-orders').getAttribute('aria-invalid'),'false');
  await page.locator('#reset-scenario').click();
  const screenshots = `.generated/verification-${Date.now()}`;
  await mkdir(screenshots,{recursive:true});
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
  await page.screenshot({path:`${screenshots}/proposal-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),'Proposal overflows on mobile');
  await page.screenshot({path:`${screenshots}/proposal-mobile.png`,fullPage:true});
  // Follow the same login journey that the client sees.
  await page.locator('a[href^="login.html?redirect=admin%2Findex.html"]').first().click();
  await page.locator('[data-fill="admin"]').click();
  await page.waitForURL('**/admin/index.html');
  assert.equal(await page.locator('.kpis .kpi').count(),4);
  const expected = await page.evaluate(()=>Store.orders().filter(o=>o.status!=='Cancelled').reduce((s,o)=>s+o.total,0));
  const shown = Number((await page.locator('.kpi-value').first().innerText()).replace(/[^\d.]/g,''));
  assert(Math.abs(expected-shown)<.01,'Order value differs from stored order totals');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('[data-day]').first().click();
  assert.match(await page.locator('#chart-detail').innerText(),/order value/);
  await page.locator('[data-metric="count"]').click();
  assert.equal(await page.locator('[data-metric="count"]').getAttribute('aria-pressed'),'true');
  await page.locator('#period').selectOption('7');
  assert.equal(await page.locator('[data-day]').count(),7);
  await page.locator('#status-filter').selectOption('Cancelled');
  assert.equal(await page.locator('.kpi-value').first().innerText(),'RM 0.00');
  assert.match(await page.locator('.analytics-table').innerText(),/No orders match/);
  await page.locator('#period').selectOption('30');
  assert.equal(await page.locator('.analytics-table [data-order]').count(),1);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-report').click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(),/30-days-cancelled\.csv/);
  const csv = await download.createReadStream();
  let text='';for await (const chunk of csv) text+=chunk;
  assert.match(text,/Cancelled/);assert.match(text,/"0.00"/);
  await page.locator('#clear-status').click();
  await page.locator('[data-category]').first().click();
  assert.match(await page.locator('#category-detail').innerText(),/units/);
  await page.locator('[data-status="Pending"]').click();
  assert.equal(await page.locator('#status-filter').inputValue(),'Pending');
  await page.locator('[data-order]').first().click();
  await page.locator('#om-status').selectOption('Processing');
  await page.locator('#om-save').click();
  assert.equal(await page.locator('.kpi-value').nth(1).innerText(),'1','Status update did not refresh dashboard');
  await page.locator('#clear-status').click();
  await page.locator('#period').selectOption('14');
  await page.locator('[data-metric="value"]').click();
  await page.locator('.toast').first().waitFor({state:'detached'});
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
  await page.screenshot({path:`${screenshots}/dashboard-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),'Dashboard overflows on mobile');
  await page.screenshot({path:`${screenshots}/dashboard-mobile.png`,fullPage:true});
  await page.locator('.admin-menu').click();
  assert(await page.locator('body').evaluate(el=>el.classList.contains('side-open')));
  // Verify existing storefront and its proposal entry point still render.
  await page.goto(base+'/index.html');
  assert.equal(await page.locator('#main-nav a[href="proposal.html"]').count(),1);
  assert((await page.locator('.product-card').count())>0);
  for (const width of [390,1024,1440]) {
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),`Storefront overflows at ${width}px`);
  }
  // Verify the shared workflows with industry-specific content and isolated data.
  await page.goto(base+'/demos.html');
  assert.equal(await page.locator('.gallery-card').count(),3);
  await page.screenshot({path:`${screenshots}/business-demos-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Demo gallery overflows on mobile');
  await page.screenshot({path:`${screenshots}/business-demos-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('a[href="index.html?demo=grocery"]').click();
  await page.waitForURL('**/index.html?demo=grocery');
  assert.match(await page.title(),/RuncitHub/);
  assert.match(await page.locator('#hero-description').innerText(),/snacks/);
  assert.equal(await page.locator('#main-nav a[href="shop.html?cat=snacks"]').count(),1);
  assert(await page.evaluate(()=>Store.orders().every(o=>o.items.every(i=>i.id.startsWith('G')))));
  await page.locator('#featured [data-add="G1001"]').click();
  assert.equal(await page.evaluate(()=>Store.cartCount()),1);
  await page.locator('#demo-profile').selectOption('automotive');
  await page.waitForURL('**/index.html?demo=automotive');
  assert.match(await page.title(),/PartsHub/);
  assert.equal(await page.evaluate(()=>Store.cartCount()),0,'Grocery cart leaked into automotive');
  assert(await page.evaluate(()=>Store.orders().every(o=>o.items.every(i=>i.id.startsWith('A')))));
  await page.goto(base+'/admin/products.html?demo=automotive');
  await page.locator('[data-edit="A1001"]').click();
  await page.locator('#f-name').fill('Workshop Demo Pad Set');
  await page.locator('#f-price').fill('88.50');
  await page.locator('#f-specs').fill('Part code: SAMPLE-01\nFitment: Verify vehicle first');
  await page.locator('#pform button[type="submit"]').click();
  await page.goto(base+'/product.html?demo=automotive&id=A1001');
  assert.equal(await page.locator('.pd-info h1').innerText(),'Workshop Demo Pad Set');
  await page.locator('[data-tab="specs"]').click();
  assert.match(await page.locator('#tab-specs').innerText(),/SAMPLE-01/);
  assert.match(await page.locator('.alert-info').innerText(),/does not validate vehicle compatibility/);
  await page.screenshot({path:`${screenshots}/automotive-product.png`,fullPage:true});
  await page.locator('#demo-profile').selectOption('grocery');
  await page.waitForURL('**/product.html?demo=grocery&id=G1001');
  assert.match(await page.locator('.pd-info h1').innerText(),/Potato Chips/);
  assert.equal(await page.evaluate(()=>Store.cartCount()),1,'Switching back did not restore grocery cart');
  await page.goto(base+'/shop.html?demo=grocery');
  assert.match(await page.locator('#price-filter').innerText(),/Under RM 10/);
  await page.locator('.search input').fill('Cream Crackers');
  await page.locator('.search button').click();
  await page.waitForURL(/shop\.html\?.*q=/);
  assert.equal(await page.locator('#results .product-card').count(),1);
  // A complete customer checkout still feeds the same profile's admin data.
  await page.goto(base+'/login.html?demo=grocery');
  await page.locator('[data-fill="user"]').click();
  await page.waitForURL('**/shop.html');
  await page.goto(base+'/checkout.html?demo=grocery');
  await page.locator('#checkout-form button[type="submit"]').click();
  await page.waitForFunction(()=>Store.orders().length===15);
  assert.equal(await page.evaluate(()=>Store.cartCount()),0);
  assert.equal(await page.evaluate(()=>Store.product('G1001').stock),119);
  await page.goto(base+'/orders.html?demo=grocery');
  assert.match(await page.locator('#orders').innerText(),/Potato Chips/);
  await page.goto(base+'/login.html?demo=grocery');
  await page.locator('[data-fill="admin"]').click();
  await page.waitForURL('**/admin/index.html');
  assert.equal(await page.evaluate(()=>Store.orders().length),15);
  assert.equal(await page.locator('#demo-profile').inputValue(),'grocery');
  await page.screenshot({path:`${screenshots}/grocery-dashboard.png`,fullPage:true});
  await page.locator('#demo-profile').selectOption('automotive');
  await page.waitForURL('**/admin/index.html?demo=automotive');
  assert.equal(await page.evaluate(()=>Store.orders().length),14,'Grocery order leaked into automotive');
  assert.equal(await page.evaluate(()=>Store.product('A1001').name),'Workshop Demo Pad Set');
  await page.locator('#demo-profile').selectOption('grocery');
  await page.waitForURL('**/admin/index.html?demo=grocery');
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#reset-demo').click();
  await page.waitForFunction(()=>Store.orders().length===14);
  assert.equal(await page.evaluate(()=>Store.product('G1001').stock),120);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('demo_automotive_products')).find(p=>p.id==='A1001').name),'Workshop Demo Pad Set','Reset affected another profile');
  const other = await page.context().newPage();
  other.on('pageerror',e=>errors.push(e.message));
  await other.goto(base+'/index.html?demo=gadgets');
  await page.goto(base+'/index.html');
  assert.equal(await page.locator('#demo-profile').inputValue(),'grocery','Another tab changed this tab\'s profile');
  assert.equal(await other.locator('#demo-profile').inputValue(),'gadgets');
  assert.equal(await other.evaluate(()=>Store.orders().length),14);
  await other.close();
  assert.deepEqual(errors,[],'Browser JavaScript errors');
  console.log('PASS: proposal, responsive layouts, analytics, CSV, 3 business profiles, product customisation, grocery checkout, data isolation, reset isolation and independent tabs.');
  console.log(`Screenshots: ${screenshots}`);
} finally {
  await browser?.close();
  await new Promise(resolve=>server.close(resolve));
}
